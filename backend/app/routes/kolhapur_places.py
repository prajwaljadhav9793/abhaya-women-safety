def search_kolhapur_places(query, limit=6):
    """Finds matching Kolhapur places by exact alias, prefix, or keyword match."""
    if not query:
        return []
    q = query.lower().strip()
    words = [w for w in q.replace(",", " ").split() if len(w) > 1]
    
    scored = []
    for item in KOLHAPUR_GAZETTEER:
        score = 0
        name_lower = item["name"].lower()
        label_lower = item["label"].lower()
        
        # 1. Exact alias match
        if any(q == k for k in item["keywords"]):
            score = 100
        # 2. Query is prefix of keyword or keyword is prefix of query
        elif any(k.startswith(q) or q.startswith(k) for k in item["keywords"]):
            score = 90
        # 3. Substring in keywords
        elif any(q in k for k in item["keywords"]):
            score = 80
        # 4. Words matching
        elif words and all(any(w in k for k in item["keywords"]) or w in name_lower or w in label_lower for w in words):
            score = 75
        elif q in name_lower:
            score = 70
        elif q in label_lower:
            score = 60
            
        if score > 0:
            scored.append((score, item))
            
    # Sort descending by match score
    scored.sort(key=lambda x: x[0], reverse=True)
    return [x[1] for x in scored[:limit]]

